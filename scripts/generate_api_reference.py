"""Render the public API reference from canonical contracts and validated, synthetic examples.

Imports do no I/O. This command never invokes Cargo, providers, or a helper.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import pathlib
import re
from urllib.parse import unquote

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONTENT = 'docs/reference/api-examples.json'
OUTPUTS = ('docs/reference/methods.md', 'docs/reference/schemas.md', 'docs/reference/http.md')
LINK_FILES = ('README.md', 'docs/README.md', 'docs/integration/api-reference.md',
              'docs/integration/generated-api.md', 'docs/integration/native-helper.md',
              'docs/integration/incremental-metadata.md', *OUTPUTS)
BANNER = '<!-- Generated by python scripts/generate_api_reference.py. Do not edit. -->'


def definitions(schema):
    return schema.get('$defs', schema.get('definitions', {}))


def anchor(name):
    return 'schema-' + name.lower()


def method_anchor(name):
    return 'method-' + name.replace('.', '-').lower()


def text(value):
    return html.escape(str(value), quote=False).replace('|', '&#124;').replace('\n', '<br>')


def type_text(value):
    if value is True or value == {}:
        return 'Any JSON value (unrestricted schema)'
    if value is False:
        return 'No JSON value'
    if '$ref' in value:
        name = value['$ref'].rsplit('/', 1)[-1]
        return f'[{name}](schemas.md#{anchor(name)})'
    if 'const' in value:
        return '`' + text(json.dumps(value['const'])) + '`'
    if 'enum' in value:
        return ', '.join('`' + text(json.dumps(item)) + '`' for item in value['enum'])
    for key in ('oneOf', 'anyOf', 'allOf'):
        if key in value:
            separator = ' AND ' if key == 'allOf' else ' OR '
            alternatives = separator.join(type_text(item) for item in value[key])
            base = {name: item for name, item in value.items() if name not in ('oneOf', 'anyOf', 'allOf')}
            if 'type' in base or 'properties' in base:
                return type_text(base) + ' AND (' + alternatives + ')'
            return alternatives
    kind = value.get('type', 'object' if 'properties' in value else None)
    if isinstance(kind, list):
        return ' OR '.join(type_text({**value, 'type': item}) for item in kind)
    if kind == 'array':
        return 'array of ' + type_text(value.get('items', True))
    if kind == 'object' and not value.get('properties') and isinstance(value.get('additionalProperties'), dict):
        return 'map of string to ' + type_text(value['additionalProperties'])
    if kind:
        return '`' + text(kind) + '`'
    if 'required' in value or 'not' in value:
        return 'Object-key constraints (expanded below)'
    return 'Any JSON value (unrestricted schema)'


def constraints(value):
    if not isinstance(value, dict):
        return ''
    parts = []
    for key in ('default', 'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum',
                'minLength', 'maxLength', 'minItems', 'maxItems', 'pattern', 'format'):
        if key in value:
            parts.append(f'{key}: `{text(json.dumps(value[key]))}`')
    return '; '.join(parts)


def table(value):
    if not isinstance(value, dict) or not value.get('properties'):
        return []
    required = set(value.get('required', []))
    lines = ['| Field | Required | Wire type | Constraints / description |',
             '|---|---|---|---|']
    for name, field in sorted(value['properties'].items()):
        description = field.get('description', '') if isinstance(field, dict) else ''
        detail = '; '.join(filter(None, [constraints(field), text(description)]))
        lines.append(f'| `{text(name)}` | {"yes" if name in required else "no"} | {type_text(field)} | {detail or "—"} |')
    additional = value.get('additionalProperties', True)
    if additional is False:
        lines += ['', 'Additional properties are forbidden by this schema.']
    else:
        lines += ['', 'This schema permits additional properties; runtime checks can be stricter.']
    return lines


def fields_for(value, names):
    if isinstance(value, dict) and '$ref' in value:
        return table(names[value['$ref'].rsplit('/', 1)[-1]])
    return table(value)


def inline_details(value, level=3):
    """Expand inline HTTP shapes without duplicating referenced domain schemas."""
    if not isinstance(value, dict) or '$ref' in value:
        return []
    lines = table(value)
    detail = constraints(value)
    if detail:
        lines += ['', detail]
    if value.get('required') and not value.get('properties'):
        lines += ['', 'Required keys for objects: ' + ', '.join('`' + text(key) + '`' for key in value['required']) + '.']
    if 'not' in value:
        lines += ['', 'Must not satisfy: `' + text(json.dumps(value['not'], sort_keys=True)) + '`.']
    for key in ('oneOf', 'anyOf', 'allOf'):
        if key in value:
            meaning = {'oneOf': 'Exactly one branch must match', 'anyOf': 'At least one branch must match',
                       'allOf': 'All branches must match'}[key]
            lines += ['', meaning + '; shared parent fields and constraints still apply.']
            for index, variant in enumerate(value[key], 1):
                lines += ['', '#' * level + f' {key} branch {index}', '', type_text(variant), '',
                          *inline_details(variant, min(level + 1, 6))]
    for name, field in value.get('properties', {}).items():
        if isinstance(field, dict) and ('properties' in field or any(key in field for key in ('oneOf', 'anyOf', 'allOf'))):
            lines += ['', '#' * level + ' Field `' + text(name) + '`', '', *inline_details(field, min(level + 1, 6))]
    return lines


def assert_local_refs(value, names):
    if isinstance(value, list):
        for item in value:
            assert_local_refs(item, names)
    elif isinstance(value, dict):
        if '$ref' in value:
            ref = value['$ref']
            if not isinstance(ref, str) or not ref.startswith('#/$defs/') or ref.rsplit('/', 1)[-1] not in names:
                raise ValueError('Only defined local schema references are accepted: ' + str(ref))
        for item in value.values():
            assert_local_refs(item, names)


def validate_value(schema, shape, value, label):
    from jsonschema import Draft202012Validator
    # References are checked before creating the validator. No retrieval or network fallback.
    wrapped = {'$defs': definitions(schema), 'allOf': [shape]}
    errors = list(Draft202012Validator(wrapped).iter_errors(value))
    if errors:
        error = errors[0]
        location = '.'.join(map(str, error.absolute_path)) or '(root)'
        raise ValueError(f'{label} at {location}: {error.message}')


def enum_values(value):
    if 'enum' in value:
        return set(value['enum'])
    if 'const' in value:
        return {value['const']}
    return set().union(*(enum_values(item) for item in value.get('oneOf', [])))


def validate_examples(schema, manifest, content):
    names = definitions(schema)
    assert_local_refs(schema, names)
    assert_local_refs(manifest, names)
    methods = {item['name']: item for item in manifest['methods']}
    examples = content['methods']
    if len(methods) != len(manifest['methods']) or set(methods) != set(examples):
        raise ValueError('Method example coverage differs from canonical methods: ' +
                         ', '.join(sorted(set(methods) ^ set(examples))))
    codes = enum_values(names['ErrorCode'])
    for name, item in methods.items():
        example = examples[name]
        for field in ('summary', 'authority', 'params', 'result', 'notes', 'errors'):
            if field not in example:
                raise ValueError(f'{name}: missing documentation field {field}')
        validate_value(schema, item['paramsSchema'], example['params'], name + ' params')
        validate_value(schema, item['resultSchema'], example['result'], name + ' result')
        for error in example['errors']:
            if error['code'] not in codes:
                raise ValueError(name + ': unknown error code ' + error['code'])
    for name, value in content.get('schemaExamples', {}).items():
        if name not in names:
            raise ValueError('Example has no canonical schema: ' + name)
        validate_value(schema, {'$ref': '#/$defs/' + name}, value, name + ' example')
    for name, extension in content.get('runtimeExtensions', {}).items():
        method = methods[extension['method']]
        query = extension['params']
        if query.get('scope') != 'inventory' or set(query) - {'scope', 'after'}:
            raise ValueError(name + ': unsupported runtime-extension example')
        validate_value(schema, method['paramsSchema'],
                       {key: value for key, value in query.items() if key != 'scope'}, name + ' base params')
        # Do not pretend a known schema gap is validated successfully. A future
        # contract fix must remove this exception and migrate the example.
        try:
            validate_value(schema, method['paramsSchema'], extension['params'], name + ' params')
        except ValueError:
            pass
        else:
            raise ValueError(name + ': documented contract gap no longer exists; update reference')
        for event in extension['result']['events']:
            validate_value(schema, {'$ref': '#/$defs/InventoryChange'}, event, name + ' event')
    encoded = json.dumps(content, ensure_ascii=False)
    if re.search(r'(?i)(?:sk-[a-z0-9]{16,}|Bearer [a-z0-9._-]{20,}|C:[/\\]Users[/\\](?!example))', encoded):
        raise ValueError('Examples must not contain credential-looking values or personal home paths')


def render_files(schema, manifest, openapi, content):
    names = definitions(schema)
    validate_examples(schema, manifest, content)
    inputs = names['MethodInputs']['properties']
    outputs = names['MethodOutputs']['properties']
    methods = manifest['methods']
    if set(inputs) != set(outputs) or set(inputs) != {item['name'] for item in methods}:
        raise ValueError('Canonical method maps disagree')
    if manifest.get('$defs') != names:
        raise ValueError('Method manifest definitions differ from canonical schema')
    for item in methods:
        if item['paramsSchema'] != inputs[item['name']] or item['resultSchema'] != outputs[item['name']]:
            raise ValueError('Method manifest shape differs from canonical schema: ' + item['name'])
    digest = hashlib.sha256(json.dumps(schema, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    intro = [BANNER, '', f'Canonical schema content SHA-256: `{digest}`.', '',
             '[API guide and safe quickstart](../integration/api-reference.md) · '
             '[Methods](methods.md) · [Schemas](schemas.md) · [HTTP routes](http.md)', '']
    method_lines = ['# JSON-RPC method reference', '', *intro,
                    f'{len(methods)} compiled method contracts. Check the actual handshake and host grants before calling them. '
                    'Examples are fictional, secret-free wire illustrations; they are not account observations or runnable credentials.', '',
                    'Each method can also fail parsing, authorization, size, or availability checks. '
                    'The listed failures are representative, not exhaustive. See '
                    '[error envelopes and recovery](../integration/api-reference.md#errors-and-recovery).', '',
                    'A JSON Schema value of `true` means **any JSON value**, not the JSON result `true`. '
                    'Such result shapes below are implementation-backed examples, not additional canonical types.', '',
                    '## Method index', '', '| Method | Purpose |', '|---|---|']
    for item in methods:
        name = item['name']
        method_lines.append(f'| [{name}](#{method_anchor(name)}) | {text(content["methods"][name]["summary"])} |')
    for index, item in enumerate(methods, 1):
        name = item['name']
        example = content['methods'][name]
        method_lines += ['', f'<a id="{method_anchor(name)}"></a>', '', f'## `{name}`', '',
                         example['summary'], '', '**Authority:** ' + example['authority'], '']
        method_lines += [('- ' + note) for note in example['notes']]
        method_lines += ['', '### Parameters', '', type_text(item['paramsSchema']), '',
                         *fields_for(item['paramsSchema'], names), '',
                         '### Result', '', type_text(item['resultSchema']), '',
                         *fields_for(item['resultSchema'], names), '', '### Example', '',
                         '**Request** (after handshake, unless this is the handshake):', '', '```json',
                         json.dumps({'jsonrpc': '2.0', 'id': index, 'method': name, 'params': example['params']}, indent=2),
                         '```', '', '**Successful response** (fictional):', '', '```json',
                         json.dumps({'jsonrpc': '2.0', 'id': index, 'result': example['result']}, indent=2), '```', '',
                         '### Representative failures', '', '| Code | Condition |', '|---|---|']
        method_lines += [f'| `{error["code"]}` | {text(error["when"])} |' for error in example['errors']]
    schema_lines = ['# Wire schema reference', '', *intro,
                    f'{len(names)} named schemas, derived from `protocol/contracts.schema.json`.', '',
                    '“Required” means the key is required by the schema. Optional and nullable are different. '
                    'Defaults describe the Rust/Serde contract, not a new permission or an automatic action. '
                    'String IDs, timestamps and decimal/count strings must retain their wire representation. '
                    'Runtime validation may impose tighter semantic bounds than the JSON Schema.', '',
                    '## Schema index', '', ' · '.join(f'[{name}](#{anchor(name)})' for name in sorted(names)), '']
    for name, value in sorted(names.items()):
        schema_lines += [f'<a id="{anchor(name)}"></a>', '', f'## `{name}`', '']
        if isinstance(value, dict) and value.get('description'):
            schema_lines += [value['description'], '']
        schema_lines += [type_text(value), '']
        detail = constraints(value)
        if detail:
            schema_lines += [detail, '']
        schema_lines += table(value)
        if isinstance(value, dict):
            for key in ('oneOf', 'anyOf', 'allOf'):
                for index, variant in enumerate(value.get(key, []), 1):
                    discriminator = [f'{k}={v["const"]}' for k, v in variant.get('properties', {}).items() if isinstance(v, dict) and 'const' in v]
                    title = ', '.join(discriminator) or f'variant {index}'
                    schema_lines += ['', f'### {title}', '', variant.get('description', ''), '', type_text(variant), '', *table(variant)]
        if name in content.get('schemaExamples', {}):
            schema_lines += ['', '### Synthetic example', '', '```json',
                             json.dumps(content['schemaExamples'][name], indent=2), '```']
        schema_lines += ['']
    http_lines = ['# Local HTTP route reference', '', *intro,
                  'Derived from `protocol/openapi.json`. These routes exist only when the host explicitly enables loopback HTTP. '
                  'Authentication is header-based; never put pairing codes, bearer tokens or credentials in a URL. '
                  'See [HTTP pairing](../integration/api-reference.md#http-pairing) before calling protected routes.', '',
                  'The OpenAPI document describes the contract subset, not every transport rejection status or runtime semantic bound. '
                  'SSE is the session event stream; use RPC for inventory journal reads.', '',
                  '## Route index', '', '| Route | Pairing / authentication |', '|---|---|']
    for path, operations in sorted(openapi['paths'].items()):
        for verb, op in operations.items():
            security = op.get('security', openapi.get('security', []))
            auth = 'Paired bearer token' if security else 'Pre-pairing local route; origin/Host checks still apply'
            route_id = 'http-' + verb + '-' + re.sub('[^a-z0-9]+', '-', path.lower()).strip('-')
            http_lines.append(f'| [{verb.upper()} `{path}`](#{route_id}) | {auth} |')
    for path, operations in sorted(openapi['paths'].items()):
        for verb, op in operations.items():
            route_id = 'http-' + verb + '-' + re.sub('[^a-z0-9]+', '-', path.lower()).strip('-')
            http_lines += ['', f'<a id="{route_id}"></a>', '', f'## {verb.upper()} `{path}`', '',
                           op.get('description', ''), '']
            for parameter in op.get('parameters', []):
                http_lines += [f'- **{parameter["in"]} `{parameter["name"]}`** '
                               f'({"required" if parameter.get("required") else "optional"}): {type_text(parameter["schema"])}.']
            for media_type, media in op.get('requestBody', {}).get('content', {}).items():
                shape = media['schema']
                # /v1/rpc alternatives are already expanded in the method reference.
                if path == '/v1/rpc':
                    http_lines += ['Request: a JSON-RPC envelope from the [method reference](methods.md).']
                else:
                    http_lines += ['', f'**Request body:** `{media_type}` — {type_text(shape)}', '', *table(shape)]
            http_lines += ['', '| Status | Meaning | Body |', '|---|---|---|']
            for status, response in op.get('responses', {}).items():
                body = '; '.join(f'`{mime}`: {type_text(media["schema"])}' for mime, media in response.get('content', {}).items())
                http_lines += [f'| {status} | {text(response.get("description", ""))} | {body or "—"} |']
            for status, response in op.get('responses', {}).items():
                for mime, media in response.get('content', {}).items():
                    details = inline_details(media['schema'], 4)
                    if details:
                        http_lines += ['', f'### Response {status}: `{mime}`', '', *details]
    return dict(zip(OUTPUTS, ('\n'.join(lines).rstrip() + '\n' for lines in (method_lines, schema_lines, http_lines))))


def load(root):
    return tuple(json.loads((root / path).read_text(encoding='utf-8')) for path in
                 ('protocol/contracts.schema.json', 'protocol/methods.json', 'protocol/openapi.json', CONTENT))


def heading_anchors(markdown):
    result = set(re.findall(r'<a\s+(?:id|name)=["\']([^"\']+)["\']', markdown))
    seen = {}
    unfenced = re.sub(r'^```.*?^```\s*$', '', markdown, flags=re.MULTILINE | re.DOTALL)
    for title in re.findall(r'^#{1,6}\s+(.+?)\s*#*$', unfenced, re.MULTILINE):
        title = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', title)
        slug = re.sub(r'[^\w\- ]', '', title.lower(), flags=re.UNICODE).replace(' ', '-')
        index = seen.get(slug, 0)
        seen[slug] = index + 1
        result.add(slug + (f'-{index}' if index else ''))
    return result


def check_links(root, paths):
    errors = []
    for path in paths:
        source = root / path
        markdown = source.read_text(encoding='utf-8')
        unfenced = re.sub(r'^```.*?^```\s*$', '', markdown, flags=re.MULTILINE | re.DOTALL)
        for target in re.findall(r'\[[^\]]*\]\(([^\s)]+)\)', unfenced):
            if re.match(r'[a-zA-Z][a-zA-Z0-9+.-]*:', target) or target.startswith('/'):
                continue
            file, _, fragment = unquote(target).partition('#')
            dest = source.parent / file if file else source
            if not dest.exists():
                errors.append(path + ': missing link ' + target)
            elif fragment and dest.suffix == '.md' and fragment not in heading_anchors(dest.read_text(encoding='utf-8')):
                errors.append(path + ': missing anchor ' + target)
    return errors


def check(root=ROOT):
    schema, manifest, openapi, content = load(root)
    rendered = render_files(schema, manifest, openapi, content)
    errors = [path + ': generated reference is stale' for path, value in rendered.items()
              if not (root / path).is_file() or (root / path).read_text(encoding='utf-8') != value]
    if not errors:
        errors += check_links(root, LINK_FILES)
        validate_guide_examples(schema, manifest, (root / 'docs/integration/api-reference.md').read_text(encoding='utf-8'))
    return errors


def validate_guide_examples(schema, manifest, markdown):
    methods = {item['name']: item for item in manifest['methods']}
    for block in re.findall(r'^```json\s*\n(.*?)^```', markdown, flags=re.MULTILINE | re.DOTALL):
        try:
            packets = [json.loads(block)]
        except json.JSONDecodeError:
            packets = [json.loads(line) for line in block.splitlines() if line.strip()]
        for packet in packets:
            if packet.get('jsonrpc') != '2.0' or 'id' not in packet:
                raise ValueError('Guide example must be an explicit JSON-RPC envelope')
            if 'method' in packet:
                method = packet['method']
                if method not in methods:
                    raise ValueError('Guide has an unknown method: ' + method)
                validate_value(schema, methods[method]['paramsSchema'], packet.get('params', {}), 'Guide ' + method)
            elif 'error' in packet:
                validate_value(schema, {'$ref': '#/$defs/DomainError'}, packet['error']['data'], 'Guide error')
            else:
                raise ValueError('Guide example has no method or typed error')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    try:
        if args.check:
            errors = check()
            if errors:
                print('\n'.join(errors))
                return 1
            print('PASS API reference: canonical methods, schemas, synthetic examples, generated files and local anchors')
        else:
            for path, value in render_files(*load(ROOT)).items():
                target = ROOT / path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(value, encoding='utf-8', newline='\n')
                print('Generated:', path)
    except (ValueError, KeyError) as error:
        print('API reference validation failed:', error)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
